from dataclasses import dataclass


@dataclass
class Indicator:
    """
    Статистический показатель для сбора данных.

    Используется парсером для идентификации целевой страницы,
    нужной секции на странице и конкретного файла для скачивания.

    Attributes:
        id (str): Уникальный идентификатор показателя
        url (str): Полный URL страницы на сайте Росстата/Мосстата
        section (str): Раздел на странице, в котором находится документ
        filename (str): Название документа, который нужно скачать
    """

    id: str
    url: str
    section: str
    filename: str
